// Generate docs/compatibility.md from the test suites' results (run in CI and before releases).
//   node compat/report.mjs            # Node suite (test keeper) + Python suite if its venv exists
// Each row is a test; the table records which keeper and runtime it passed on.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rows = [];
function tap(label, cwd, env = {}) {
  const files = fs.readdirSync(path.join(cwd, 'test')).filter((f) => f.endsWith('.test.mjs')).sort();
  for (const f of files) {
    const r = spawnSync(process.execPath, ['--test', '--test-reporter=tap', `test/${f}`], { cwd, env: { ...process.env, ...env }, encoding: 'utf8' });
    for (const m of r.stdout.matchAll(/^(not ok|ok) \d+ - (.*?)(?: # (SKIP|TODO)(.*))?$/gm)) {
      if (m[2] === `test/${f}`) continue;
      rows.push({ suite: f.replace('.test.mjs', ''), name: m[2], [label]: m[3] ? 'skip' : m[1] === 'ok' ? 'pass' : 'FAIL' });
    }
  }
}
function py(label, env = {}) {
  const venv = path.join(ROOT, 'compat/python/.venv/bin/python');
  if (!fs.existsSync(venv)) return;
  const r = spawnSync(venv, ['-m', 'unittest', '-v', 'test_compat'], { cwd: path.join(ROOT, 'compat/python'), env: { ...process.env, ...env }, encoding: 'utf8' });
  for (const m of r.stderr.matchAll(/^(test_\w+) \(test_compat\.(\w+)\.\w+\)(?:\n.*?)? \.\.\. (ok|FAIL|ERROR|skipped.*)$/gm)) {
    rows.push({ suite: `python:${m[2]}`, name: m[1].replace(/^test_/, '').replace(/_/g, ' '), [label]: m[3] === 'ok' ? 'pass' : m[3].startsWith('skipped') ? 'skip' : 'FAIL' });
  }
}
const rust = path.join(ROOT, 'target/debug/doppelkeyd');
tap('node-keeper', path.join(ROOT, 'compat/node'));
py('node-keeper');
if (fs.existsSync(rust)) {
  tap('doppelkeyd', path.join(ROOT, 'compat/node'), { DOPPELKEY_KEEPER_CMD: `${rust} insecure-test-keeper` });
  py('doppelkeyd', { DOPPELKEY_KEEPER_CMD: `${rust} insecure-test-keeper` });
}
const merged = new Map();
for (const r of rows) {
  const k = `${r.suite}\u0000${r.name}`;
  merged.set(k, { ...(merged.get(k) || {}), ...r });
}
const mark = (v) => (v === 'pass' ? '✅' : v === 'skip' ? '–' : v === 'FAIL' ? '❌' : ' ');
const lines = [
  '# Compatibility',
  '',
  `Generated by \`node compat/report.mjs\` on ${new Date().toISOString().slice(0, 10)} with Node ${process.version}. Every row is an oracle-pattern test: the app runs with handles and the shim, and a separate process holding the real keys verifies the output. – means skipped (for example, root bypasses the memory-protection check; CI runs it as a normal user).`,
  '',
  '| Suite | Test | Node test keeper | doppelkeyd |',
  '| --- | --- | :-: | :-: |',
  ...[...merged.values()].map((r) => `| ${r.suite} | ${r.name.replace(/\|/g, '\\|')} | ${mark(r['node-keeper'])} | ${mark(r.doppelkeyd)} |`),
  '',
];
fs.writeFileSync(path.join(ROOT, 'docs/compatibility.md'), lines.join('\n'));
const failed = [...merged.values()].filter((r) => r['node-keeper'] === 'FAIL' || r.doppelkeyd === 'FAIL').length;
console.log(`wrote docs/compatibility.md: ${merged.size} tests, ${failed} failing`);
process.exit(failed ? 1 : 0);
