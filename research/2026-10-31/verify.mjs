import fs from 'node:fs';
import { unsealData } from 'iron-session';
import { decode as naDecode } from 'next-auth/jwt';
import { symmetricDecodeJWT } from 'better-auth/crypto';
const A = 'real-auth-secret-for-hkdf-7c1e3a5b9d2f4e6a8c0b';
const s = JSON.parse(fs.readFileSync('shim.json')).out, r = JSON.parse(fs.readFileSync('real.json')).out;
for (const k of ['octokit', 'svix', 'oslo', 'hono', 'betterAuthSig']) console.log(k.padEnd(14), k in s ? (s[k] === r[k] ? 'MATCHES real key' : 'WRONG (silently signed with handle text)') : 'error');
const chk = async (k, f) => { if (!(k in s)) return console.log(k.padEnd(14), 'error'); try { const v = await f(s[k]); console.log(k.padEnd(14), v ? 'decrypts with real key' : 'does NOT decrypt with real key'); } catch (e) { console.log(k.padEnd(14), 'does NOT decrypt with real key:', e.message.slice(0, 60)); } };
await chk('betterAuthJWE', async (t) => (await symmetricDecodeJWT(t, A, 'salt'))?.sub === 'u');
await chk('ironSeal', async (t) => (await unsealData(t, { password: A, ttl: 0 }))?.u === 'alice');
await chk('nextAuthV4', async (t) => (await naDecode({ token: t, secret: A }))?.sub === 'u');
